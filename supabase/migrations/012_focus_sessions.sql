create table if not exists focus_sessions (
  id uuid primary key,   -- generated by the client for idempotency
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  habit_id uuid references habits(id) on delete set null,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  duration_seconds integer not null check (duration_seconds between 60 and 43200),
  planned_seconds integer check (planned_seconds is null or planned_seconds > 0),
  mode text not null check (mode in ('countdown','pomodoro')),
  local_date date not null,
  habit_minutes_applied numeric not null default 0,
  created_at timestamptz not null default now(),
  check (ended_at > started_at)
);

create index if not exists focus_sessions_user_date on focus_sessions (user_id, local_date);

alter table focus_sessions enable row level security;

-- select / delete: auth.uid() = user_id. No update policy.
drop policy if exists "Users can select own focus sessions" on focus_sessions;
create policy "Users can select own focus sessions" on focus_sessions
  for select
  using (auth.uid() = user_id);

drop policy if exists "Users can delete own focus sessions" on focus_sessions;
create policy "Users can delete own focus sessions" on focus_sessions
  for delete
  using (auth.uid() = user_id);

-- insert: with check (auth.uid() = user_id and (habit_id is null or exists
--   (select 1 from habits h where h.id = habit_id and h.user_id = auth.uid())))
drop policy if exists "Users can insert own focus sessions" on focus_sessions;
create policy "Users can insert own focus sessions" on focus_sessions
  for insert
  with check (
    auth.uid() = user_id and (
      habit_id is null or exists (
        select 1 from habits h where h.id = habit_id and h.user_id = auth.uid()
      )
    )
  );

-- Function 1: log_focus_session (SECURITY INVOKER so RLS applies, runs in one transaction)
create or replace function log_focus_session(
  p_id uuid,
  p_habit_id uuid,
  p_started timestamptz,
  p_ended timestamptz,
  p_planned integer,
  p_mode text,
  p_local_date date
)
returns void
language plpgsql
security invoker
as $$
declare
  v_user_id uuid := auth.uid();
  v_duration_seconds integer;
  v_habit record;
  v_amount_to_apply numeric := 0;
  v_day_entry_id uuid;
  v_comp record;
  v_target_snapshot numeric;
  v_new_amount numeric;
  v_is_completed boolean;
  v_inserted_id uuid;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  v_duration_seconds := extract(epoch from (p_ended - p_started))::integer;
  if v_duration_seconds < 60 then
    return; -- Ignore sessions under 60 seconds
  end if;
  if v_duration_seconds > 43200 then
    v_duration_seconds := 43200; -- Cap at 12 hours
  end if;

  -- Check if habit exists and is an amount habit with unit min or hours
  if p_habit_id is not null then
    select * into v_habit
    from habits
    where id = p_habit_id and user_id = v_user_id;

    if found and v_habit.type = 'amount' and v_habit.unit is not null then
      if lower(v_habit.unit) in ('hours', 'hour', 'hr', 'hrs', 'h') then
        -- Convert minutes to hours (2 decimal places)
        v_amount_to_apply := round((v_duration_seconds / 3600.0)::numeric, 2);
      elsif lower(v_habit.unit) in ('min', 'mins', 'minute', 'minutes', 'm') then
        -- Minutes (1 decimal place)
        v_amount_to_apply := round((v_duration_seconds / 60.0)::numeric, 1);
      end if;
    end if;
  end if;

  -- 1. Insert session (idempotent; on conflict do nothing)
  insert into focus_sessions (
    id,
    user_id,
    habit_id,
    started_at,
    ended_at,
    duration_seconds,
    planned_seconds,
    mode,
    local_date,
    habit_minutes_applied,
    created_at
  ) values (
    p_id,
    v_user_id,
    p_habit_id,
    p_started,
    p_ended,
    v_duration_seconds,
    p_planned,
    p_mode,
    p_local_date,
    v_amount_to_apply,
    now()
  )
  on conflict (id) do nothing
  returning id into v_inserted_id;

  -- If nothing was inserted (already logged), return immediately
  if v_inserted_id is null then
    return;
  end if;

  -- 2. If habit amount applied > 0, upsert day_entries and day_habit_completions
  if p_habit_id is not null and v_amount_to_apply > 0 then
    -- Upsert day_entries
    insert into day_entries (user_id, date)
    values (v_user_id, p_local_date)
    on conflict (date, user_id) do update set updated_at = now()
    returning id into v_day_entry_id;

    if v_day_entry_id is null then
      select id into v_day_entry_id from day_entries where user_id = v_user_id and date = p_local_date;
    end if;

    -- Look up existing completion row
    select * into v_comp
    from day_habit_completions
    where day_entry_id = v_day_entry_id and habit_id = p_habit_id and user_id = v_user_id;

    if found then
      v_target_snapshot := coalesce(v_comp.target_snapshot, v_habit.target_value);
      v_new_amount := coalesce(v_comp.amount, 0) + v_amount_to_apply;
      v_is_completed := case
        when v_target_snapshot is not null and v_target_snapshot > 0 then (v_new_amount >= v_target_snapshot)
        else false
      end;

      update day_habit_completions
      set amount = v_new_amount,
          target_snapshot = v_target_snapshot,
          is_completed = v_is_completed
      where id = v_comp.id;
    else
      v_target_snapshot := v_habit.target_value;
      v_new_amount := v_amount_to_apply;
      v_is_completed := case
        when v_target_snapshot is not null and v_target_snapshot > 0 then (v_new_amount >= v_target_snapshot)
        else false
      end;

      insert into day_habit_completions (
        day_entry_id,
        habit_id,
        user_id,
        amount,
        target_snapshot,
        is_completed,
        is_skipped
      ) values (
        v_day_entry_id,
        p_habit_id,
        v_user_id,
        v_new_amount,
        v_target_snapshot,
        v_is_completed,
        false
      );
    end if;
  end if;
end;
$$;

-- Function 2: delete_focus_session (SECURITY INVOKER so RLS applies, runs in one transaction)
create or replace function delete_focus_session(p_id uuid)
returns void
language plpgsql
security invoker
as $$
declare
  v_session record;
  v_day_entry_id uuid;
  v_comp record;
  v_new_amount numeric;
  v_new_completed boolean;
begin
  -- Fetch session (verifying user ownership via RLS)
  select * into v_session
  from focus_sessions
  where id = p_id and user_id = auth.uid();

  if not found then
    return;
  end if;

  -- Delete session
  delete from focus_sessions where id = p_id and user_id = auth.uid();

  -- If session had habit minutes/amount applied
  if v_session.habit_id is not null and v_session.habit_minutes_applied > 0 then
    select id into v_day_entry_id
    from day_entries
    where user_id = auth.uid() and date = v_session.local_date;

    if v_day_entry_id is not null then
      select * into v_comp
      from day_habit_completions
      where day_entry_id = v_day_entry_id and habit_id = v_session.habit_id and user_id = auth.uid();

      if found then
        v_new_amount := greatest(0, coalesce(v_comp.amount, 0) - v_session.habit_minutes_applied);
        v_new_completed := case
          when v_comp.target_snapshot is not null and v_comp.target_snapshot > 0 then (v_new_amount >= v_comp.target_snapshot)
          else false
        end;

        update day_habit_completions
        set amount = v_new_amount,
            is_completed = v_new_completed
        where id = v_comp.id;
      end if;
    end if;
  end if;
end;
$$;

